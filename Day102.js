// 🟢 Question 1 – Variables and Data Types
// Topics: var, let, const, typeof, console.log().
// Write a JavaScript program to:
// 1. Create a variable name with the value "Siva".
// 2. Create a variable age with the value 22.
// 3. Create a variable isDeveloper with the value true.
// 4. Create a variable salary with the value 25000.
// 5. Print all four variables using console.log().
// 6. Print the data type of each variable using typeof.
// Expected Output:
// Siva
// 23
// true
// 25000
// string
// number
// boolean
// number
// Conditions:
// - Use JavaScript only.
// - Use console.log() to display the output.
// - Use typeof to check the data types.

let name = "Siva";
let age = 22;
let isDeveloper = true;
let salary = 25000;

console.log(name);
console.log(age);
console.log(isDeveloper);
console.log(salary);

console.log(typeof name);
console.log(typeof age);
console.log(typeof isDeveloper);
console.log(typeof salary);


